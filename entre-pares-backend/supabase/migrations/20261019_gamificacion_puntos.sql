-- Entre Pares: movimientos de puntos con control de duplicados.
-- Revisar y ejecutar en Supabase SQL Editor después de verificar el esquema.
-- Esta migración NO se ejecuta automáticamente desde el frontend.

create table if not exists public.movimientos_puntos (
    id bigint generated by default as identity primary key,
    perfil_id uuid not null references public.perfiles(id) on delete cascade,
    referencia_id uuid not null,
    evento text not null check (evento in (
        'tutoria_finalizada',
        'calificacion_estudiante',
        'calificacion_tutor',
        'contribucion_aprobada',
        'canje'
    )),
    puntos integer not null,
    descripcion text not null,
    creado_at timestamptz not null default now(),
    constraint movimientos_puntos_evento_unico unique (perfil_id, referencia_id, evento)
);

create index if not exists idx_movimientos_puntos_perfil_fecha
    on public.movimientos_puntos (perfil_id, creado_at desc);

alter table public.movimientos_puntos enable row level security;

drop policy if exists "Cada usuario puede ver sus movimientos de puntos"
    on public.movimientos_puntos;

create policy "Cada usuario puede ver sus movimientos de puntos"
    on public.movimientos_puntos
    for select
    to authenticated
    using (perfil_id = auth.uid());

-- Función interna: solo suma puntos si el movimiento aún no existe.
create or replace function public.registrar_movimiento_puntos(
    p_perfil_id uuid,
    p_referencia_id uuid,
    p_evento text,
    p_puntos integer,
    p_descripcion text
) returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    if p_perfil_id is null or p_referencia_id is null or p_puntos = 0 then
        return;
    end if;

    insert into public.movimientos_puntos
        (perfil_id, referencia_id, evento, puntos, descripcion)
    values
        (p_perfil_id, p_referencia_id, p_evento, p_puntos, p_descripcion)
    on conflict (perfil_id, referencia_id, evento) do nothing;

    if found then
        update public.perfiles
        set puntos_gamificacion = greatest(0, coalesce(puntos_gamificacion, 0) + p_puntos)
        where id = p_perfil_id;
    end if;
end;
$$;

-- Otorga 20 puntos a ambas partes cuando una reserva pasa a Finalizada.
create or replace function public.puntos_por_tutoria_finalizada()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if new.estado = 'Finalizada'
       and old.estado is distinct from new.estado then
        perform public.registrar_movimiento_puntos(
            new.estudiante_id, new.id, 'tutoria_finalizada', 20,
            'Puntos por tutoría finalizada'
        );
        perform public.registrar_movimiento_puntos(
            new.tutor_id, new.id, 'tutoria_finalizada', 20,
            'Puntos por tutoría finalizada'
        );
    end if;
    return new;
end;
$$;

drop trigger if exists trg_puntos_tutoria_finalizada on public.reservas;
create trigger trg_puntos_tutoria_finalizada
after update of estado on public.reservas
for each row
execute function public.puntos_por_tutoria_finalizada();

-- Otorga 5 puntos a quien envía la calificación. La restricción única evita
-- volver a otorgarlos si se intenta registrar otra vez para la misma reserva.
create or replace function public.puntos_por_calificacion()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_autor uuid;
    v_evento text;
begin
    if coalesce(new.calificado_por, 'estudiante') = 'tutor' then
        v_autor := new.tutor_id;
        v_evento := 'calificacion_tutor';
    else
        v_autor := new.estudiante_id;
        v_evento := 'calificacion_estudiante';
    end if;

    perform public.registrar_movimiento_puntos(
        v_autor, new.reserva_id, v_evento, 5,
        'Puntos por calificar una tutoría'
    );
    return new;
end;
$$;

drop trigger if exists trg_puntos_por_calificacion on public.resenas;
create trigger trg_puntos_por_calificacion
after insert on public.resenas
for each row
execute function public.puntos_por_calificacion();

-- No se crean canjes automáticos ni se modifica el catálogo de recompensas:
-- antes hay que definir las recompensas, su costo y el proceso de confirmación.


-- Catálogo de recompensas y registro de canjes.
create table if not exists public.recompensas (
    id uuid primary key default gen_random_uuid(),
    nombre text not null,
    descripcion text,
    costo_puntos integer not null check (costo_puntos > 0),
    activa boolean not null default true,
    creado_at timestamptz not null default now()
);

create table if not exists public.canjes (
    id uuid primary key default gen_random_uuid(),
    perfil_id uuid not null references public.perfiles(id) on delete cascade,
    recompensa_id uuid not null references public.recompensas(id),
    costo_puntos integer not null check (costo_puntos > 0),
    estado text not null default 'Confirmado' check (estado in ('Confirmado', 'Cancelado')),
    creado_at timestamptz not null default now()
);

create index if not exists idx_canjes_perfil_fecha
    on public.canjes (perfil_id, creado_at desc);

alter table public.recompensas enable row level security;
alter table public.canjes enable row level security;

drop policy if exists "Todos pueden ver recompensas activas" on public.recompensas;
create policy "Todos pueden ver recompensas activas"
    on public.recompensas for select
    to authenticated
    using (activa = true);

drop policy if exists "Cada usuario puede ver sus canjes" on public.canjes;
create policy "Cada usuario puede ver sus canjes"
    on public.canjes for select
    to authenticated
    using (perfil_id = auth.uid());

-- La operación se realiza en una transacción y bloquea el perfil para evitar
-- que dos canjes simultáneos gasten el mismo saldo.
create or replace function public.canjear_recompensa(p_recompensa_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
    v_perfil_id uuid := auth.uid();
    v_puntos integer;
    v_recompensa public.recompensas%rowtype;
    v_canje_id uuid;
begin
    if v_perfil_id is null then
        raise exception 'Debés iniciar sesión para canjear una recompensa.';
    end if;

    select puntos_gamificacion
      into v_puntos
      from public.perfiles
     where id = v_perfil_id
     for update;

    if not found then
        raise exception 'No se encontró el perfil del usuario.';
    end if;

    select *
      into v_recompensa
      from public.recompensas
     where id = p_recompensa_id
       and activa = true;

    if not found then
        raise exception 'La recompensa no existe o no está disponible.';
    end if;

    if coalesce(v_puntos, 0) < v_recompensa.costo_puntos then
        raise exception 'No tenés puntos suficientes para este canje.';
    end if;

    insert into public.canjes (perfil_id, recompensa_id, costo_puntos)
    values (v_perfil_id, v_recompensa.id, v_recompensa.costo_puntos)
    returning id into v_canje_id;

    perform public.registrar_movimiento_puntos(
        v_perfil_id,
        v_canje_id,
        'canje',
        -v_recompensa.costo_puntos,
        'Canje de recompensa: ' || v_recompensa.nombre
    );

    return v_canje_id;
end;
$$;

-- El helper solo debe usarse internamente por funciones/trigger confiables.
revoke all on function public.registrar_movimiento_puntos(uuid, uuid, text, integer, text) from public, anon, authenticated;
revoke all on function public.canjear_recompensa(uuid) from public, anon;
grant execute on function public.canjear_recompensa(uuid) to authenticated;
