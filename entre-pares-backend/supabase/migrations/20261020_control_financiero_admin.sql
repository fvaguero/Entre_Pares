-- Control financiero administrativo: fechas reales e historial de cambios.
-- Revisar y ejecutar manualmente en Supabase SQL Editor antes de usar el panel.

ALTER TABLE public.reservas
  ADD COLUMN IF NOT EXISTS fecha_pago timestamptz,
  ADD COLUMN IF NOT EXISTS fecha_liquidacion timestamptz;

CREATE TABLE IF NOT EXISTS public.historial_pagos_admin (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reserva_id uuid NOT NULL REFERENCES public.reservas(id) ON DELETE CASCADE,
  cambiado_por uuid NULL REFERENCES public.perfiles(id) ON DELETE SET NULL,
  estado_anterior text,
  estado_nuevo text NOT NULL,
  fecha_cambio timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_historial_pagos_reserva_fecha
  ON public.historial_pagos_admin (reserva_id, fecha_cambio DESC);

ALTER TABLE public.historial_pagos_admin ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Administradores pueden consultar historial de pagos"
  ON public.historial_pagos_admin;

CREATE POLICY "Administradores pueden consultar historial de pagos"
  ON public.historial_pagos_admin
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.perfiles p
      WHERE p.id = auth.uid() AND p.rol = 'Administrador'
    )
  );

CREATE OR REPLACE FUNCTION public.registrar_cambio_estado_pago_admin()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.estado_pago IS DISTINCT FROM OLD.estado_pago THEN
    -- Fecha del pago recibido. No usar la fecha de la tutoría como sustituto.
    IF lower(coalesce(NEW.estado_pago, '')) IN ('pagado', 'pagada', 'completada', 'completado') THEN
      IF lower(coalesce(OLD.estado_pago, '')) NOT IN ('pagado', 'pagada', 'completada', 'completado') THEN
        NEW.fecha_pago := now();
      END IF;
      NEW.fecha_liquidacion := NULL;
    ELSIF lower(coalesce(NEW.estado_pago, '')) IN ('liquidado', 'liquidada', 'transferido', 'transferida') THEN
      NEW.fecha_pago := coalesce(NEW.fecha_pago, now());
      NEW.fecha_liquidacion := now();
    ELSIF lower(coalesce(NEW.estado_pago, '')) IN ('pendiente', 'pendiente de pago', 'a pagar', '') THEN
      NEW.fecha_pago := NULL;
      NEW.fecha_liquidacion := NULL;
    END IF;

    INSERT INTO public.historial_pagos_admin
      (reserva_id, cambiado_por, estado_anterior, estado_nuevo, fecha_cambio)
    VALUES
      (NEW.id, auth.uid(), OLD.estado_pago, coalesce(NEW.estado_pago, 'Pendiente'), now());
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_historial_estado_pago_admin ON public.reservas;
CREATE TRIGGER trg_historial_estado_pago_admin
BEFORE UPDATE OF estado_pago ON public.reservas
FOR EACH ROW
EXECUTE FUNCTION public.registrar_cambio_estado_pago_admin();

-- Backfill conservador: no se inventan fechas históricas para pagos ya existentes.
-- Las fechas se completan a partir de ahora cuando cambie el estado correspondiente.

GRANT SELECT ON public.historial_pagos_admin TO authenticated;
